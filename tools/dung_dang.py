"""mega-shot · `xp pose-editor` (old name `xp dung-dang`) — FK pose & clip editor for the code-drawn 2D characters + the shared custom clip library.

  xp pose-editor mo [--nv <id>] [--clip <name>] [--port 8765]   → local editor (engine/core/xuong_dung_dang.html) with a save route; Ctrl+C to stop
  xp pose-editor them <file.json> [--name <name>]                → install a clip the AI wrote ({len, loop, keys: [[t, {channels}, easing?]], …})
  xp pose-editor soat <name> [--nv <id>] [--n 8]                 → <lib>/clips/<name>_soat.jpg: n frames side by side (review without opening a browser)
  xp pose-editor ds | xoa <name>                                 → list | remove
  (English action aliases: open = mo, add = them, check = soat, list = ds, remove = xoa)

Library: .mega-shot/nhanvat/clips/<name>.json (source of truth) → engine/core/nhanvat_clip_rieng.js (generated, loaded by the truyen
template, xuong_sheet.html and the editor), so `clip: <name>` works in video.yaml hanh_dong like any built-in clip.
Ideas taken from ArtCraft (github.com/storytold/artcraft, MIT/Apache-2.0): FK bone posing, timeline clip strips with
bezier transitions (`chuyen`), deterministic playhead evaluation. No ArtCraft code is copied; its Mixamo / MMD motion data
is NOT licensed and is not used.
"""
import base64, http.server, json, os, re, sys, threading

NAME = re.compile(r'^[a-z0-9][a-z0-9-]{1,40}$')


def lib(X):
    d = os.path.join(X.find_root(os.getcwd()), '.mega-shot', 'nhanvat', 'clips'); os.makedirs(d, exist_ok=True); return d


def kiem(c):
    """validate a clip: keys sorted, numeric channels known to the rig, easing names known → list of problems"""
    loi = []
    if not isinstance(c.get('keys'), list) or not c['keys']: return ['keys is empty']
    KN = set('rot dx dy hh hf sp sb tw nk hr hy sh aNp aNa aNe aFp aFa aFe gN gF kN kF oN oF lNp lNa lNk lNf lFp lFa lFk lFf pN pF'.split())
    EZ = {'lin', 'giu', 'vao', 'ra', 'vao-ra', 'nhanh-cham', 'cham-nhanh', 'nay', 'lay-da', 'lay-da-nay'}
    last = -1
    for i, k in enumerate(c['keys']):
        if not isinstance(k, list) or len(k) < 2: loi.append(f'key {i}: must be [t, {{channels}}, (easing)]'); continue
        if k[0] < last: loi.append(f'key {i}: time goes backwards')
        last = k[0]
        for ch, v in k[1].items():
            if ch not in KN: loi.append(f'key {i}: unknown channel {ch}')
            elif not isinstance(v, (int, float)): loi.append(f'key {i}: {ch} is not a number')
            elif ch[0] in 'al' and ch[-1] in 'pake' and abs(v) > 3.3: loi.append(f'key {i}: {ch}={v} rad is too large')
        if len(k) > 2 and k[2] is not None and not (k[2] in EZ or (isinstance(k[2], list) and len(k[2]) == 4)): loi.append(f'key {i}: unknown easing {k[2]}')
    if c.get('len') is not None and c['len'] < last: loi.append(f"len {c['len']} < last key {last}")
    return loi


def sinh_js(X):
    """rebuild engine/core/nhanvat_clip_rieng.js from the library"""
    d = lib(X); clips = {}
    for f in sorted(os.listdir(d)):
        if f.endswith('.json'):
            try: clips[f[:-5]] = json.load(open(os.path.join(d, f), encoding='utf-8'))
            except Exception as e: X.log(f'⚠ skipping {f}: {e}')
    body = json.dumps(clips, ensure_ascii=False, separators=(',', ':'))
    p = os.path.join(X.SKILL, 'engine', 'core', 'nhanvat_clip_rieng.js')
    open(p, 'w', encoding='utf-8').write('// mega-shot · nhanvat_clip_rieng.js — custom clips made with the pose editor (xuong_dung_dang.html) or written by the AI.\n'
        '// GENERATED by `xp pose-editor` from .mega-shot/nhanvat/clips/*.json — do not edit by hand. Load right after nhanvat_clip.js.\n'
        f'window.__RIENG = {json.dumps(sorted(clips))};\n'
        f'(() => {{ if (!window.MS || !MS.nv) return; MS.nv.addClips({body}); }})();\n')
    return len(clips)


def luu(X, ten, c):
    if not NAME.match(ten): raise ValueError('clip name: lowercase ASCII letters, digits and hyphens (e.g. vay-tay-2)')
    loi = kiem(c)
    if loi: raise ValueError('; '.join(loi[:6]))
    json.dump(c, open(os.path.join(lib(X), ten + '.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    return sinh_js(X)


def server(X, port):
    eng = os.path.join(X.SKILL, 'engine', 'core'); root = X.find_root(os.getcwd())

    class H(http.server.SimpleHTTPRequestHandler):
        def __init__(s, *a, **k): super().__init__(*a, directory=eng, **k)
        def log_message(s, *a): pass
        def end_headers(s): s.send_header('Cache-Control', 'no-store'); super().end_headers()   # editing tool: always serve the latest engine files
        def do_GET(s):
            if s.path in ('/', '/index.html'): s.send_response(302); s.send_header('Location', '/xuong_hanh_dong.html'); s.end_headers(); return
            if s.path == '/nv/ds':   # library characters for the preview's picker
                d = os.path.join(root, '.mega-shot', 'nhanvat'); out = []
                for n in sorted(os.listdir(d)) if os.path.isdir(d) else []:
                    sp = os.path.join(d, n, 'spec.json'); cat = os.path.join(d, n, 'nhanvat.json')
                    if os.path.exists(cat):   # cut-out character (xp redraw rig): parts in <id>/bo/
                        try: out.append({'id': n, 'ten': json.load(open(cat, encoding='utf-8')).get('ten') or n, 'kieu': 'cat', 'khoa': False}); continue
                        except Exception: pass
                    if os.path.exists(sp):
                        try: out.append({'id': n, 'ten': json.load(open(sp, encoding='utf-8')).get('ten') or n, 'khoa': os.path.exists(os.path.join(d, n, 'khoa.json'))})
                        except Exception: pass
                b = json.dumps(out, ensure_ascii=False).encode(); s.send_response(200); s.send_header('Content-Type', 'application/json'); s.send_header('Content-Length', str(len(b))); s.end_headers(); s.wfile.write(b); return
            m = re.match(r'^/nv/([a-z0-9-]+)/(spec\.json|bo/[A-Za-z0-9_.-]+)$', s.path.split('?')[0])
            if m:
                p = os.path.join(root, '.mega-shot', 'nhanvat', m.group(1), *m.group(2).split('/'))
                if not os.path.exists(p): return s.send_error(404)
                b = open(p, 'rb').read(); s.send_response(200); s.send_header('Content-Type', 'image/png' if p.endswith('.png') else 'application/json'); s.send_header('Content-Length', str(len(b))); s.end_headers(); s.wfile.write(b); return
            return super().do_GET()
        def do_POST(s):
            if s.path != '/luu': return s.send_error(404)
            try:
                o = json.loads(s.rfile.read(int(s.headers.get('Content-Length', 0))).decode('utf-8')); n = luu(X, o['ten'], o['clip'])
                msg = f'ok ({n} clips in the library)'.encode(); s.send_response(200); X.log(f"💾 saved clip {o['ten']}")
            except Exception as e: msg = str(e).encode('utf-8'); s.send_response(400)
            s.send_header('Content-Length', str(len(msg))); s.end_headers(); s.wfile.write(msg)
    return http.server.ThreadingHTTPServer(('127.0.0.1', port), H)


def soat(X, ten, nvid, n):
    from playwright.sync_api import sync_playwright
    if not ten: X.die('missing clip name: xp pose-editor soat <name>')
    srv = server(X, 0); threading.Thread(target=srv.serve_forever, daemon=True).start()
    out = os.path.join(lib(X), ten + '_soat.jpg'); cat = nvid and os.path.exists(os.path.join(X.find_root(os.getcwd()), '.mega-shot', 'nhanvat', nvid, 'nhanvat.json'))
    qs = f'?clip={ten}&soat=1' + (f'&nv={nvid}' if nvid else '') + ('&cat=1' if cat else '')
    with sync_playwright() as pw:
        b = pw.chromium.launch(args=['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist']); pg = b.new_page(viewport={'width': 1400, 'height': 1000})
        errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.goto(f'http://127.0.0.1:{srv.server_port}/xuong_dung_dang.html{qs}'); pg.set_default_timeout(300_000); pg.wait_for_function('window.READY === true')
        if pg.evaluate(f'!MS.nv.CLIPS[{json.dumps(ten)}]'): b.close(); srv.shutdown(); sys.exit(f'no clip named {ten}')
        pg.evaluate(f'window.dai({n})')
        open(out, 'wb').write(base64.b64decode(pg.evaluate("document.getElementById('c').toDataURL('image/jpeg', .9).split(',')[1]")))
        b.close()
    srv.shutdown(); print(f'{out}' + (f'  ⚠ page errors: {errs[:2]}' if errs else ''))


def main(a, X):
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    if a.action == 'mo':
        sinh_js(X); s = server(X, a.port)
        qs = '&'.join(f'{k}={v}' for k, v in (('nv', a.nv), ('clip', a.clip)) if v)
        print(f'Action preview: http://127.0.0.1:{a.port}/xuong_hanh_dong.html' + ('?' + qs if qs else ''))
        print(f'Pose editor:    http://127.0.0.1:{a.port}/xuong_dung_dang.html' + ('?' + qs if qs else '') + '   (Ctrl+C to stop)', flush=True)
        try: s.serve_forever()
        except KeyboardInterrupt: pass
    elif a.action == 'them':
        if not a.ten_hoac_file: X.die('missing clip file: xp pose-editor them <file.json>')
        c = json.load(open(a.ten_hoac_file, encoding='utf-8'))
        if 'keys' not in c and len(c) == 1: (ten, c), = c.items()
        else: ten = a.name or os.path.splitext(os.path.basename(a.ten_hoac_file))[0]
        ten = a.name or ten; n = luu(X, ten, c); print(f'added clip {ten} ({n} clips) → use clip: {ten} in hanh_dong')
    elif a.action == 'soat': soat(X, a.ten_hoac_file, a.nv, a.n)
    elif a.action == 'ds':
        d = lib(X)
        for f in sorted(os.listdir(d)):
            if f.endswith('.json'): c = json.load(open(os.path.join(d, f), encoding='utf-8')); print(f"  {f[:-5]:<22} {c.get('len', '?')} s · {len(c['keys'])} keys" + (' · loop' if c.get('loop') else '') + (' · upper body' if c.get('tren') else ''))
    elif a.action == 'xoa':
        if not a.ten_hoac_file: X.die('missing clip name: xp pose-editor xoa <name>')
        p = os.path.join(lib(X), a.ten_hoac_file + '.json')
        if os.path.exists(p): os.remove(p); print('removed', a.ten_hoac_file, '·', sinh_js(X), 'clips left')
        else: print('no clip named', a.ten_hoac_file)
